CREATE OR REPLACE PROCEDURE BOOK_VENUE (
    P_BOOKING_ID IN NUMBER,
    P_EVENT_ID   IN NUMBER,
    P_VENUE_ID   IN NUMBER
)
IS
    V_PARTICIPANTS EVENTS.PARTICIPANTS%TYPE;
    V_CAPACITY     VENUES.CAPACITY%TYPE;
    V_AVAILABLE    VENUES.AVAILABLE%TYPE;
BEGIN
    SELECT PARTICIPANTS
      INTO V_PARTICIPANTS
      FROM EVENTS
     WHERE EVENT_ID = P_EVENT_ID;

    SELECT CAPACITY, AVAILABLE
      INTO V_CAPACITY, V_AVAILABLE
      FROM VENUES
     WHERE VENUE_ID = P_VENUE_ID
       FOR UPDATE;

    IF V_AVAILABLE <> 'Y' THEN
        RAISE_APPLICATION_ERROR(-20001, 'Venue is not available.');
    END IF;

    IF V_CAPACITY < V_PARTICIPANTS THEN
        RAISE_APPLICATION_ERROR(-20002, 'Venue capacity is insufficient.');
    END IF;

    INSERT INTO BOOKINGS (BOOKING_ID, EVENT_ID, VENUE_ID, BOOKING_DATE)
    VALUES (P_BOOKING_ID, P_EVENT_ID, P_VENUE_ID, SYSDATE);

    UPDATE VENUES
       SET AVAILABLE = 'N'
     WHERE VENUE_ID = P_VENUE_ID;

    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Venue booked successfully.');

EXCEPTION
    WHEN NO_DATA_FOUND THEN
        ROLLBACK;
        DBMS_OUTPUT.PUT_LINE('Event or venue ID was not found.');
    WHEN OTHERS THEN
        ROLLBACK;
        RAISE;
END;
/
