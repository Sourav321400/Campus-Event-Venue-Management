CREATE OR REPLACE FUNCTION CALCULATE_EVENT_FEE (
    P_PARTICIPANTS IN NUMBER
) RETURN NUMBER
IS
    V_RATE NUMBER;
BEGIN
    IF P_PARTICIPANTS <= 50 THEN
        V_RATE := 100;
    ELSIF P_PARTICIPANTS <= 100 THEN
        V_RATE := 80;
    ELSE
        V_RATE := 60;
    END IF;

    RETURN P_PARTICIPANTS * V_RATE;
END;
/
