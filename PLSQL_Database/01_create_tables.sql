-- Campus Event and Venue Management System
-- Run in your Oracle schema.

CREATE TABLE EVENTS (
    EVENT_ID NUMBER PRIMARY KEY,
    EVENT_NAME VARCHAR2(100) NOT NULL,
    EVENT_DATE DATE NOT NULL,
    PARTICIPANTS NUMBER NOT NULL CHECK (PARTICIPANTS > 0)
);

CREATE TABLE VENUES (
    VENUE_ID NUMBER PRIMARY KEY,
    VENUE_NAME VARCHAR2(100) NOT NULL,
    CAPACITY NUMBER NOT NULL CHECK (CAPACITY > 0),
    AVAILABLE CHAR(1) DEFAULT 'Y' CHECK (AVAILABLE IN ('Y', 'N'))
);

CREATE TABLE BOOKINGS (
    BOOKING_ID NUMBER PRIMARY KEY,
    EVENT_ID NUMBER NOT NULL,
    VENUE_ID NUMBER NOT NULL,
    BOOKING_DATE DATE DEFAULT SYSDATE,
    CONSTRAINT FK_BOOKING_EVENT FOREIGN KEY (EVENT_ID) REFERENCES EVENTS(EVENT_ID),
    CONSTRAINT FK_BOOKING_VENUE FOREIGN KEY (VENUE_ID) REFERENCES VENUES(VENUE_ID)
);

CREATE TABLE BOOKING_AUDIT (
    AUDIT_ID NUMBER PRIMARY KEY,
    BOOKING_ID NUMBER,
    OPERATION VARCHAR2(20),
    MODIFIED_BY VARCHAR2(128),
    CHANGE_DATE DATE
);
