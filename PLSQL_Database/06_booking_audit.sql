CREATE SEQUENCE AUDIT_SEQ
START WITH 1
INCREMENT BY 1
NOCACHE;

CREATE OR REPLACE TRIGGER TRG_BOOKING_AUDIT
AFTER DELETE ON BOOKINGS
FOR EACH ROW
BEGIN
    INSERT INTO BOOKING_AUDIT (
        AUDIT_ID, BOOKING_ID, OPERATION, MODIFIED_BY, CHANGE_DATE
    )
    VALUES (
        AUDIT_SEQ.NEXTVAL,
        :OLD.BOOKING_ID,
        'DELETE',
        USER,
        SYSDATE
    );
END;
